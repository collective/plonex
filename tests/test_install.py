    def test_requirements_and_constraints_merge_from_profiles(self):
        with temp_cwd() as cwd:
            install = InstallService(dont_ask=True)

            base_profile = cwd / "profiles" / "base"
            child_profile = cwd / "profiles" / "child"
            (base_profile / "etc" / "requirements.d").mkdir(parents=True)
            (base_profile / "etc" / "constraints.d").mkdir(parents=True)
            (child_profile / "etc" / "requirements.d").mkdir(parents=True)
            (child_profile / "etc" / "constraints.d").mkdir(parents=True)

            (base_profile / "etc" / "plonex.yml").write_text("{}\n")
            (child_profile / "etc" / "plonex.yml").write_text(
                "profiles:\n  - ../base\n"
            )
            (install.etc_folder / "plonex.yml").write_text(
                "profiles:\n  - profiles/child\n"
            )

            (base_profile / "etc" / "requirements.d" / "010-base.txt").write_text(
                "base-req\n"
            )
            (child_profile / "etc" / "requirements.d" / "010-child.txt").write_text(
                "child-req\n"
            )
            (install.requirements_d_folder / "010-local.txt").write_text("local-req\n")

            (base_profile / "etc" / "constraints.d" / "010-base.txt").write_text(
                "shared==1.0.0\nbasepkg==1.0.0\n"
            )
            (child_profile / "etc" / "constraints.d" / "010-child.txt").write_text(
                "shared==2.0.0\nchildpkg==2.0.0\n"
            )
            (install.constraints_d_folder / "010-local.txt").write_text(
                "shared==3.0.0\nlocalpkg==3.0.0\n"
            )

            with stub_virtualenv(install):
                with mock_remote_constraints():
                    with install:
                        requirements_line = (
                            install.requirements_txt.read_text().splitlines()
                        )
                        self.assertEqual(
                            requirements_line.pop(9),
                            f"-r {cwd / 'etc' / 'requirements.d' / '010-local.txt'}",
                        )
                        self.assertEqual(
                            requirements_line.pop(9),
                            f"-r {child_profile / 'etc' / 'requirements.d' / '010-child.txt'}",  # noqa: E501
                        )
                        self.assertEqual(
                            requirements_line.pop(9),
                            f"-r {base_profile / 'etc' / 'requirements.d' / '010-base.txt'}",  # noqa: E501
                        )
                        self.assertEqual(
                            "\n".join(requirements_line), self.default_requirements_file
                        )
                        self.assertCountEqual(
                            install.constrainst_txt.read_text().splitlines(),
                            [
                                "# This file is generated by plonex",
                                "basepkg==1.0.0",
                                "childpkg==2.0.0",
                                "localpkg==3.0.0",
                                "shared==3.0.0",
                            ],
                        )

