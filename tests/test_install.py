@contextmanager
def stub_virtualenv(install):
    """Create a minimal .venv stub to avoid real virtualenv creation in tests."""
    venv_bin = install.target / ".venv" / "bin"
    venv_bin.mkdir(parents=True, exist_ok=True)
    (venv_bin / "activate").touch()
    (venv_bin / "uv").touch()
    with mock.patch.object(install, "ensure_virtualenv"):
        yield


@contextmanager
def temp_install(**kwargs):
    with temp_cwd():
        kwargs["dont_ask"] = True
        install = InstallService(**kwargs)
        with stub_virtualenv(install), mock_remote_constraints():
            with install:
                yield install


@contextmanager
def mock_remote_constraints(mapping=None):
    mapping = mapping or {}

    def fake_get(url, timeout):
        response = mock.Mock()
        response.text = mapping.get(url, "")
        response.headers = {"Content-Type": "text/plain"}
        response.raise_for_status = mock.Mock()
        return response

    with mock.patch("plonex.services.install.requests.get", side_effect=fake_get):
        yield


