    def test_constraint_fragments_use_filename_order(self):
        with temp_cwd():
            install = InstallService(dont_ask=True)
            (install.constraints_d_folder / "a.txt").write_text("bar==1.0.0")
            (install.constraints_d_folder / "z.txt").write_text("bar==0.8.0")
            original_iterdir = Path.iterdir

            def reverse_constraint_directory(path):
                entries = list(original_iterdir(path))
                if path == install.constraints_d_folder:
                    entries.sort(reverse=True)
                return iter(entries)

            with mock.patch.object(Path, "iterdir", reverse_constraint_directory):
                with mock_remote_constraints():
                    install.make_constraints_txt()
            lines = install.constrainst_txt.read_text().splitlines()
            self.assertIn("bar==1.0.0", lines)
            self.assertNotIn("bar==0.8.0", lines)

    def test_requirements(self):
        """Check that we can properly merge the requirements files"""
        with temp_cwd():
            install = InstallService(dont_ask=True)

            (install.requirements_d_folder / "foo.txt").write_text("foo")
            (install.requirements_d_folder / "bar.txt").write_text("bar")
            (install.constraints_d_folder / "foo.txt").write_text("foo==1.0.0")
            (install.constraints_d_folder / "bar_obsolete.txt").write_text("bar==0.8.0")
            (install.constraints_d_folder / "bar.txt").write_text("bar==1.0.0")
            (install.constraints_d_folder / "bar_py38.txt").write_text(
                "bar==0.9.0; python_version == '3.8'"
            )
            with stub_virtualenv(install):
                with mock_remote_constraints():
                    with install:
                        requirements_lines = (
                            install.requirements_txt.read_text().splitlines()
                        )
                        self.assertEqual(
                            requirements_lines.pop(9),
                            f"-r {str(install.requirements_d_folder)}/bar.txt",
                        )
                        self.assertEqual(
                            requirements_lines.pop(9),
                            f"-r {str(install.requirements_d_folder)}/foo.txt",
                        )
                        self.assertEqual(
                            "\n".join(requirements_lines),
                            self.default_requirements_file,
                        )
                        self.assertCountEqual(
                            install.constrainst_txt.read_text().splitlines(),
                            [
                                "# This file is generated by plonex",
                                "bar==1.0.0",
                                'bar==0.9.0; python_version == "3.8"',
                                "foo==1.0.0",
                            ],
                        )

