    def test_collect_constraints_expands_remote_includes_and_skips_cycles(self):
        url = "https://example.org/pins/base.txt"
        with temp_cwd() as cwd:
            install = InstallService(dont_ask=True)
            root = cwd / "root.txt"
            root.write_text(f"-c {url}\nLocal.Pkg==3.0\n")
            nested = cwd / "nested.txt"
            nested.write_text(f"-c {root}\nNested.Pkg==4.0\n")
            # Local nesting and repeated remote references exercise cycle handling.
            root.write_text(root.read_text() + f"-c {nested}\n-c {url}\n")
            with mock_remote_constraints(
                {
                    url: "-r /extra.txt\nZope.Sendmail==7.2\n",
                    "https://example.org/extra.txt": "Other.Pkg==2.0\n",
                }
            ):
                includes, entries = install._collect_constraint_entries(
                    root, developed_packages={"other-pkg"}
                )
            self.assertCountEqual(
                includes, [f"-c {url}", "-r https://example.org/extra.txt"]
            )
            self.assertCountEqual(
                [install._normalize_requirement_dump(req) for req in entries.values()],
                ["local-pkg==3.0", "nested-pkg==4.0", "zope-sendmail==7.2"],
            )

