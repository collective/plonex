    def test_normalize_requirement_preserves_versions_urls_and_markers(self):
        marker = '; sys_platform == "Win32"'
        extras_spec = f"Demo.Pkg[My_Extra, Other.Extra]{marker}"
        extras_expected = f"demo-pkg[my-extra,other-extra]{marker}"
        archive = "https://Example.org/Some_Path.whl"
        vcs = "git+https://Example.org/My_Repo.git@Main#subdirectory=My_Dir"
        cases = {
            "Zope.Sendmail==7.2": "zope-sendmail==7.2",
            "Foo__Bar..BAZ>=1.0RC1": "foo-bar-baz>=1.0RC1",
            "Foo.Bar (==1.0)": "foo-bar (==1.0)",
            "Foo.Bar # comment": "foo-bar # comment",
            extras_spec: extras_expected,
            f"My.Pkg @ {archive}": f"my-pkg @ {archive}",
            f"My.Pkg @ {vcs}": f"my-pkg @ {vcs}",
            "--editable /tmp/My_Project": "--editable /tmp/My_Project",
            "./My_Project": "./My_Project",
            "My_Package-1.0-py3-none-any.whl": "My_Package-1.0-py3-none-any.whl",
            "My_Package-1.0.tar.gz": "My_Package-1.0.tar.gz",
            "https://Example.org/My_Package.whl": "https://Example.org/My_Package.whl",
            "-c My_Constraints.txt": "-c My_Constraints.txt",
            "# My_Comment": "# My_Comment",
        }
        for spec, expected in cases.items():
            with self.subTest(spec=spec):
                self.assertEqual(normalize_requirement(spec), expected)

