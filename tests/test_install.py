    def test_remote_html_warns_and_preserves_previous_constraints(self):
        url = "https://github.com/example/pins/blob/main/constraints.txt"
        cases = [
            ({"Content-Type": "text/html; charset=utf-8"}, "Login required"),
            ({"Content-Type": "application/xhtml+xml"}, "Login required"),
            ({}, "<!DOCTYPE HTML>\n<html>web page</html>"),
            ({"Content-Type": "text/plain"}, "<!-- comment -->\n<HTML>page</HTML>"),
        ]
        for headers, body in cases:
            with self.subTest(headers=headers, body=body), temp_cwd():
                install = InstallService(
                    dont_ask=True, cli_options={"plonex_base_constraint": url}
                )
                previous = install.var_folder / "constraints.txt"
                previous.write_text("old-pin==1.0\n")
                response = mock.Mock(text=body, headers=headers)
                with (
                    mock.patch(
                        "plonex.services.install.requests.get", return_value=response
                    ),
                    mock.patch.object(install.logger, "warning") as warning,
                ):
                    with self.assertRaisesRegex(ValueError, "returned HTML"):
                        install.make_constraints_txt()
                self.assertIn("raw.githubusercontent.com", warning.call_args.args[0])
                self.assertIn(url, warning.call_args.args[0])
                self.assertEqual(previous.read_text(), "old-pin==1.0\n")
                self.assertEqual(list(install.tmp_folder.iterdir()), [])

